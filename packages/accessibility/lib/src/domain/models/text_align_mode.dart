/// The horizontal text alignment override.
enum TextAlignMode {
  /// Do not override the alignment.
  none,

  /// Align to the leading edge.
  start,

  /// Align to the trailing edge.
  end,

  /// Align left.
  left,

  /// Align right.
  right,

  /// Center.
  center,

  /// Stretch lines to the full width.
  justify,
}
